export function t(english: string): string {
  const leading = english.startsWith(" ") ? " " : "";
  const trailing = english.endsWith(" ") ? " " : "";
  const key = english.trim();
  const translated =
    typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("tr")
      ? (tr[key] ?? tr[english] ?? key)
      : key;
  return `${leading}${translated.trim().replaceAll("&rsquo;", "’")}${trailing}`;
}

export function tf(english: string, values: Record<string, string | number>): string {
  return t(english).replace(/\{(\w+)\}/g, (all, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : all,
  );
}

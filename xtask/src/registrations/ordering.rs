use super::*;
use std::path::PathBuf;

type Order = BTreeMap<String, Vec<String>>;
const PATH: &str = "xtask/src/registrations/order.json";

fn key(section: &str, tokens: &TokenStream) -> Result<String> {
    if section == "owner_actions" {
        let arm: syn::Arm = syn::parse2(tokens.clone())?;
        return Ok(source::tokens(&arm.pat)
            .chars()
            .filter(|c| !c.is_whitespace())
            .collect());
    }
    source::strings(tokens)
        .into_iter()
        .next()
        .ok_or_else(|| format!("{section} has no stable key").into())
}

pub(super) fn apply(root: &Path, registration: &mut Registration) -> Result {
    let order: Order = serde_json::from_str(&fs::read_to_string(root.join(PATH))?)?;
    for (section, entries) in &mut registration.sections {
        let mut indices = entries.keys().copied().collect::<Vec<_>>();
        if let Some(keys) = order.get(section) {
            let mut seen = BTreeSet::new();
            for tokens in entries.values() {
                if !seen.insert(key(section, tokens)?) {
                    return Err(format!("duplicate ordered {section} entry").into());
                }
            }
            indices.sort_by_key(|index| {
                keys.iter()
                    .position(|k| *k == key(section, &entries[index]).unwrap())
                    .unwrap_or(usize::MAX)
            });
        }
        // A wildcard must be explicitly declared as fallback; its position never depends on domain order.
        if let Some(fallbacks) = registration.fallbacks.get(section) {
            indices.sort_by_key(|index| fallbacks.contains(index));
        }
        let old_fallbacks = registration.fallbacks.remove(section).unwrap_or_default();
        let old_sources = registration.sources.remove(section).unwrap_or_default();
        let old = std::mem::take(entries);
        for (index, previous) in indices.into_iter().enumerate() {
            entries.insert(index, old[&previous].clone());
            if old_fallbacks.contains(&previous) {
                registration.fallbacks.entry(section.clone()).or_default().insert(index);
            }
            if let Some(raw) = old_sources.get(&previous) {
                registration
                    .sources
                    .entry(section.clone())
                    .or_default()
                    .insert(index, raw.clone());
            }
        }
    }
    Ok(())
}

pub(super) fn outputs(root: &Path, registration: &Registration) -> Result<Vec<(PathBuf, String)>> {
    let mut order: Order = serde_json::from_str(&fs::read_to_string(root.join(PATH))?)?;
    for (section, keys) in &mut order {
        *keys = registration.sections[section]
            .values()
            .map(|tokens| key(section, tokens))
            .collect::<Result<_>>()?;
    }
    let command_order = format!(
        "// Generated by cargo xtask registrations.\nconst COMMAND_ORDER: &[&str] = &[\n{}\n];\n",
        order["commands"]
            .iter()
            .map(|key| format!("{key:?},"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    Ok(vec![
        (PATH.into(), serde_json::to_string_pretty(&order)? + "\n"),
        (
            "crates/pinchora-commands/src/commands/registration/command_order.rs".into(),
            output::format(root, &command_order)?,
        ),
    ])
}
